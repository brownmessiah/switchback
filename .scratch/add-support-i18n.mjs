const locales = Object.keys(T)
for (const locale of locales) {
  const filePath = join(MESSAGES_DIR, `${locale}.json`)
  const json = JSON.parse(readFileSync(filePath, 'utf-8'))
  if (!json.CustomerNav) {
    throw new Error(`${locale}.json missing CustomerNav anchor — aborting`)
  }
  // Rebuild the object inserting SupportPage immediately after CustomerNav,
  // preserving all other key order.
  const rebuilt = {}
  for (const [key, value] of Object.entries(json)) {
    rebuilt[key] = value
    if (key === 'CustomerNav') {
      rebuilt.SupportPage = T[locale]
    }
  }
  writeFileSync(filePath, JSON.stringify(rebuilt, null, 2) + '\n', 'utf-8')
  console.log(`✓ ${locale}.json — SupportPage namespace added`)
}
console.log(`Done: ${locales.length} locales updated`)
